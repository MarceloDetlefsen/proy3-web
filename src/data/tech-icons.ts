function normalizeTechName(value: string): string {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, "");
}

export function getTechIcon(tech: string): SimpleIcon | null {
  return TECH_ICON_MAP[normalizeTechName(tech)] ?? null;
}

export function getTechIconSvg(tech: string): string | null {
  return getTechIcon(tech)?.svg ?? null;
}
